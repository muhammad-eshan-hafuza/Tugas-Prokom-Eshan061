def show_messages(messages):
    """Mencetak semua pesan yang ada di dalam list."""
    for message in messages:
        print(message)

daftar_pesan = [
    "Halo, selamat pagi!",
    "Kuliah Pengantar Teknik Industri jam 10 ya.",
    "Jangan lupa kerjakan tugas Python!"
]

show_messages(daftar_pesan)