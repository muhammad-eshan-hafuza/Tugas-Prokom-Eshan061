makanan = ['pizza', 'burger', 'mie ayam', 'bakso', 'nasi goreng']

# 1. Tiga item pertama
print("Tiga item pertama dalam list adalah:")
print(makanan[:3])

# 2. Tiga item di tengah (indeks 1 sampai 4)
print("\nTiga item dari bagian tengah list adalah:")
print(makanan[1:4])

# 3. Tiga item terakhir
print("\nTiga item terakhir dalam list adalah:")
print(makanan[-3:])