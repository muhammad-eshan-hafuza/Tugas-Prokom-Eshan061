# 1. Membuat list hewan peliharaan berkaki empat
animals = ['anjing', 'kucing', 'kelinci']

# 2. Mencetak kalimat tentang masing-masing hewan
for animal in animals:
    print(f"Seekor {animal} akan menjadi hewan peliharaan yang hebat.")

# 3. Kesamaan hewan-hewan tersebut (di luar loop)
print("Semua hewan ini bisa menjadi hewan peliharaan yang menyenangkan!")